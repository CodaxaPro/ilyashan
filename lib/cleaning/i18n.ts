const tables: Record<CleaningLocale, Dict> = { de, tr };

export function t(locale: CleaningLocale, key: string, vars?: Record<string, string | number>): string {
  let s = tables[locale][key] ?? tables.de[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, String(v));
    }
  }
  return s;
}
